import { fileURLToPath } from 'node:url';
import { isAbsolute, relative, resolve, sep } from 'node:path';

import react from '@astrojs/react';
import mdx from '@astrojs/mdx';
import type { AstroIntegration, AstroIntegrationLogger } from 'astro';

import { parseDatabaseUrl } from './runtime/database.js';
import type { DashtroResolvedConfig } from './runtime/types.js';
import { dashtroVitePlugin } from './vite-plugin.js';

export interface DashtroOptions {
  /** Database URL. Prefer this name. */
  database_url?: string;
  /** Alias of {@link database_url}. */
  databaseUrl?: string;
  /** Alias of {@link database_url}. */
  database?: string;
  /** Directory scanned for `.sql` queries. Defaults to `<srcDir>/queries`. */
  queriesDir?: string;
  /** URL path of the query API endpoint. Defaults to `/api/dashtro/query`. */
  apiPath?: string;
  /** Open DuckDB files read-only. Defaults to `true`. */
  readOnly?: boolean;
  /** Maximum number of pooled Postgres connections. Defaults to `4`. */
  poolSize?: number;
  /** Set to `false` to stop dashtro from adding `@astrojs/react`. Defaults to `true`. */
  react?: boolean;
  /** Set to `false` to stop dashtro from adding `@astrojs/mdx`. Defaults to `true`. */
  mdx?: boolean;
}

/**
 * Dashtro Astro integration.
 *
 * ```js
 * // astro.config.mjs
 * import dashtro from 'dashtro';
 *
 * export default defineConfig({
 *   integrations: [dashtro({ database_url: 'duckdb:./data/analytics.duckdb' })],
 * });
 * ```
 */
export default function dashtro(options: DashtroOptions = {}): AstroIntegration {
  return {
    name: 'dashtro',
    hooks: {
      'astro:config:setup': ({ config, updateConfig, injectRoute, logger }) => {
        const resolved = resolveOptions(options, config.root, config.srcDir);

        const addedIntegrations: AstroIntegration[] = [];
        if (options.react !== false && !hasIntegration(config.integrations, '@astrojs/react')) {
          addedIntegrations.push(react());
        }
        if (options.mdx !== false && !hasIntegration(config.integrations, '@astrojs/mdx')) {
          addedIntegrations.push(mdx());
        }

        const queriesGlob = toQueriesGlob(resolved, logger);

        updateConfig({
          ...(addedIntegrations.length > 0 ? { integrations: addedIntegrations } : {}),
          vite: {
            plugins: [
              dashtroVitePlugin({
                config: resolved,
                queriesGlob,
              }),
            ],
            ssr: {
              external: ['@duckdb/node-api', 'pg'],
              // Bundle dashtro so that Vite resolves its `react`/`react-dom`
              // imports through `resolve.dedupe`. Without this, a locally linked
              // copy of dashtro loads its own React from its own `node_modules`
              // and React reports an invalid hook call.
              noExternal: ['dashtro'],
            },
          },
        });

        if (config.output === 'static') {
          logger.warn(
            'dashtro: `output` is "static", so the query API endpoint is disabled. Switch to an SSR adapter to refresh data without a page reload.',
          );
        } else {
          injectRoute({
            pattern: resolved.apiPath,
            entrypoint: 'dashtro/routes/query',
          });
        }

        logger.info(
          `database: ${resolved.dialect} (${redactUrl(resolved.databaseUrl)}), queries: ${relative(resolved.rootDir, resolved.queriesDir) || '.'}, api: ${resolved.apiPath}`,
        );
      },

      'astro:config:done': ({ injectTypes }) => {
        injectTypes({
          filename: 'dashtro.d.ts',
          content: INJECTED_TYPES,
        });
      },
    },
  };
}

const INJECTED_TYPES = `// Generated by dashtro. Do not edit.
declare module '*.sql' {
  import type { DashtroQuery } from 'dashtro/runtime';
  const query: DashtroQuery;
  export default query;
  export { query };
}

declare module 'virtual:dashtro/queries' {
  export function loadAllQueries(): Promise<void>;
}

declare module 'virtual:dashtro/config' {
  import type { DashtroResolvedConfig } from 'dashtro/runtime';
  const config: DashtroResolvedConfig;
  export default config;
}
`;

function resolveOptions(options: DashtroOptions, root: URL, srcDir: URL): DashtroResolvedConfig {
  const databaseUrl =
    options.database_url ??
    options.databaseUrl ??
    options.database ??
    process.env.DASHTRO_DATABASE_URL ??
    process.env.DATABASE_URL;

  if (!databaseUrl) {
    throw new Error(
      'dashtro: `database_url` is required. Pass it to the integration, for example: dashtro({ database_url: "duckdb:./data/analytics.duckdb" }).',
    );
  }

  const rootDir = fileURLToPath(root);
  const srcPath = fileURLToPath(srcDir);
  const { dialect } = parseDatabaseUrl(databaseUrl);

  const queriesDir = options.queriesDir
    ? isAbsolute(options.queriesDir)
      ? options.queriesDir
      : resolve(rootDir, options.queriesDir)
    : resolve(srcPath, 'queries');

  let apiPath = options.apiPath ?? '/api/dashtro/query';
  if (!apiPath.startsWith('/')) {
    apiPath = `/${apiPath}`;
  }

  return {
    rootDir,
    databaseUrl,
    dialect,
    apiPath,
    queriesDir,
    readOnly: options.readOnly ?? true,
    poolSize: options.poolSize ?? 4,
  };
}

function toQueriesGlob(
  config: DashtroResolvedConfig,
  logger: AstroIntegrationLogger,
): string | null {
  const relativeDir = relative(config.rootDir, config.queriesDir);

  if (relativeDir.startsWith('..')) {
    logger.warn(
      `dashtro: queriesDir (${config.queriesDir}) is outside the project root. The API endpoint cannot discover queries automatically; import them from a page instead.`,
    );
    return null;
  }

  const posix = relativeDir.split(sep).join('/');
  return posix ? `/${posix}/**/*.sql` : '/**/*.sql';
}

function hasIntegration(integrations: AstroIntegration[], name: string): boolean {
  return integrations.some((integration) => integration.name === name);
}

function redactUrl(url: string): string {
  return url.replace(/\/\/([^:@/]+):([^@/]+)@/, '//$1:***@');
}
